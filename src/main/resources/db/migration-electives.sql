CREATE TABLE IF NOT EXISTS public.student_elective_enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_profile_id UUID NOT NULL,
    course_offering_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_student_elective_enrollment
        UNIQUE (student_profile_id, course_offering_id),
    CONSTRAINT fk_student_elective_enrollment_student
        FOREIGN KEY (student_profile_id)
        REFERENCES public.student_profiles(student_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_student_elective_enrollment_offering
        FOREIGN KEY (course_offering_id)
        REFERENCES public.course_offerings(offering_id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_student_elective_enrollments_student
    ON public.student_elective_enrollments (student_profile_id);

CREATE INDEX IF NOT EXISTS idx_student_elective_enrollments_offering
    ON public.student_elective_enrollments (course_offering_id);

CREATE INDEX IF NOT EXISTS idx_student_elective_enrollments_student_offering
    ON public.student_elective_enrollments (student_profile_id, course_offering_id);

CREATE OR REPLACE FUNCTION public.ensure_elective_enrollment_offering_type()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM public.course_offerings co
        WHERE co.offering_id = NEW.course_offering_id
          AND co.offering_type = 'ELECTIVE'
    ) THEN
        RAISE EXCEPTION 'Student elective enrollment must reference an ELECTIVE course offering.';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_student_elective_enrollment_offering_type
    ON public.student_elective_enrollments;

CREATE TRIGGER trg_student_elective_enrollment_offering_type
BEFORE INSERT OR UPDATE OF course_offering_id
ON public.student_elective_enrollments
FOR EACH ROW
EXECUTE FUNCTION public.ensure_elective_enrollment_offering_type();
